#!/usr/bin/env bash
# Паритет классификации внешних программ у гейта публикации.
#
# Инвариант: гейт разбирает ФОРМУ shell-команды. Содержимое программ, которые
# команда запускает, в предмет разбора не входит — это заявленный предел
# контракта, той же семьи, что уже принятый предел commit-гейта.
#
# Отсюда требование паритета: запуск файла-скрипта оболочкой (`bash x.sh`)
# классифицируется так же, как запуск любой другой внешней программы, читающей
# файл (`python3 x.py`, `npm run …`). Пока паритета не было, самая частая
# команда разработчика получала другой вердикт, чем равносильный по
# возможностям запуск интерпретатора.
#
# Вторая половина проверки — что паритет не расползся: нагрузка, заданная
# строкой в самой команде, взятая со стандартного входа или собранная
# раскрытием, по-прежнему разбирается гейтом, потому что она ЧАСТЬ команды, а не
# содержимое внешней программы.
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
. "$ROOT/scripts/tests/lib/assert.sh"

PYTHON_RUNNER="$ROOT/.claude/tools/run-python.sh"
HOOK="$ROOT/.claude/hooks/check-merge-ready.py"

# Вердикт гейта для одной команды: 0 — обычная команда, 2 — команда разбирается
# и её тело проверяется.
verdict() {
  local payload
  payload="$("$PYTHON_RUNNER" -c 'import json,sys; print(json.dumps({"tool_input":{"command":sys.argv[1]}}))' "$1")"
  printf '%s' "$payload" | env -u FINALIZE_PR_TOKEN "$PYTHON_RUNNER" "$HOOK" >/dev/null 2>&1
  printf '%s\n' "$?"
}

# --- 1. Эталон паритета: чем меряем ------------------------------------------
# Запуск интерпретатора с файлом — обычная команда. Это опорная точка: к ней
# приводится запуск файла оболочкой.

assert_eq "$(verdict 'python3 scripts/check-doc-authority.py')" "0" \
  "эталон: запуск интерпретатора с файлом — обычная команда"
assert_eq "$(verdict 'npm run test')" "0" \
  "эталон: запуск сборщика — обычная команда"

# --- 2. Запуск файла оболочкой — обычная команда ------------------------------

SCRIPT_RUNS=(
  'самая частая команда разработчика:bash scripts/tests/run-all.sh'
  'короткое имя оболочки:sh script.sh'
  'zsh:zsh script.zsh'
  'dash:dash script.sh'
  'относительный путь с аргументами:bash ./x.sh arg1 arg2'
  'флаги оболочки перед путём:bash -e -u -x script.sh'
  'слитные флаги и аргументы скрипта:bash -eux ./deploy.sh --flag value'
  'разделитель опций перед путём:bash -- script.sh'
  'известная опция с операндом перед путём:bash --init-file rc.sh script.sh'
  'путь с каталогами:bash scripts/deploy/vps.sh production'
)
for entry in "${SCRIPT_RUNS[@]}"; do
  title="${entry%%:*}"
  command="${entry#*:}"
  assert_eq "$(verdict "$command")" "0" \
    "запуск файла оболочкой — обычная команда ($title)"
done

# --- 3. Нагрузка, заданная в самой команде, разбирается ------------------------
# Здесь программа не читается из файла: она записана в команде, пришла на
# стандартный вход или собирается раскрытием. Такая нагрузка — часть формы
# команды, поэтому гейт её разбирает.

INSPECTED=(
  'строкой в самой команде:bash -c '\''gh pr comment 1 --body "Готов к merge"'\'''
  'строкой у короткой оболочки:sh -c '\''gh pr comment 1 --body "Готов к merge"'\'''
  'строкой при слитных флагах:bash -lc '\''gh pr comment 1 --body "Готов к merge"'\'''
  'со стандартного входа при -s:bash -s arg'
  'со стандартного входа при дефисе:bash -'
  'путь из переменной:bash "$SCRIPT"'
  'путь из подстановки:bash $(echo x.sh)'
  'подстановка процесса в позиции файла:bash <(echo '\''gh pr comment 1 --body "Готов к merge"'\'')'
)
for entry in "${INSPECTED[@]}"; do
  title="${entry%%:*}"
  command="${entry#*:}"
  assert_eq "$(verdict "$command")" "2" \
    "нагрузка внутри команды разбирается ($title)"
done

# --- 4. Публикация в самой команде проверяется как прежде ----------------------
# Паритет касается только запуска внешних программ. Сама публикация в команде
# разбирается ровно как раньше — иначе проверка выше ничего не значила бы.

assert_eq "$(verdict 'gh pr comment 645 --body "Готов к merge"')" "2" \
  "публикация с формулировкой готовности разбирается"
assert_eq "$(verdict 'gh pr comment 645 --body "обычный отчёт ревью"')" "0" \
  "публикация без формулировки готовности проходит"
assert_eq "$(verdict 'bash scripts/tests/run-all.sh && gh pr comment 645 --body "Готов к merge"')" "2" \
  "публикация рядом с запуском скрипта разбирается"

finish
