#!/usr/bin/env bash
# Гейт тестов перед коммитом.
#
# Почему отдельный скрипт, а не инлайн-команда в settings.json:
# matcher хука фильтрует ТОЛЬКО имя инструмента (контракт hooks Claude Code).
# Матчер сведён к `Bash`, а единственный семантический классификатор живёт в
# `commit_command_classifier.py`. Отдельный `if` запрещён: более узкий prefilter
# становится второй истиной и не вызывает handler для wrapper/path/carrier-форм.
#
# Коды выхода: 0 — пропустить; 2 — заблокировать. Только 2 блокирует PreToolUse,
# код 1 считается неблокирующей ошибкой и команда выполняется.
#
# Почему у гейта СВОЙ предел времени, а не только объявленный в settings.json:
# по своему лимиту диспетчер снимает обработчик. Снятый обработчик не возвращает
# кода выхода, а блокирует только код 2 — то есть коммит проходил бы при
# недоказанном результате тестов. Поэтому и РАЗБОР команды, и прогон набора идут
# под собственными пределами, а по их истечении гейт сам возвращает 2:
# недоказанная зелёность — не зелёность. Ambiguous command блокируется сразу и не запускает тяжёлый suite.
#
# БЮДЖЕТ ФАЗ ПОД СОБСТВЕННЫМИ ПРЕДЕЛАМИ (обязан уложиться в предел, объявленный
# диспетчеру в .claude/settings.json — 600 с):
#   разбор команды                    ≤  10 с  (CLASSIFY_TIMEOUT_SECONDS)
#   добивание группы после разбора    ≤   2 с  (grace обёртки: TERM, +1 с, KILL)
#   прогон набора тестов              ≤ 570 с  (GATE_TIMEOUT_SECONDS)
#   добивание группы после прогона    ≤   2 с  (тот же grace)
#   запуск интерпретаторов и печать   ≈   1 с
#   ---------------------------------------------
#   итого                             ≤ 585 с  < 600 с, запас ≥ 15 с
#
# ⚠️ Слово «ПОЛНЫЙ» здесь было бы неверным, и это не придирка к формулировке.
# Таблица покрывает только фазы, идущие ПОД собственными пределами. Фаза чтения
# payload (`PAYLOAD="$(cat)"` ниже) обёртки времени не имеет и в таблицу не
# входит: окружение, оставившее stdin открытым, подвешивает обработчик, и
# никакое число здесь этого не ограничивает. Дефект существовал до калибровки и
# ею не вносится — рост объявленного предела лишь удлиняет ожидание до того же
# неблокирующего исхода. Заведён отдельной задачей U2-dn7qh.
#
# Арифметика проверяется тестом scripts/tests/commit-gate-parse-budget.test.sh —
# включая сам запас 15 с: прежде тот тест допускал РАВЕНСТВО бюджета и
# объявленного предела, то есть нулевой запас, и обещание этой таблицы не
# удерживалось ничем. Соотношение 570 < 600 и потолок 600 — тестом
# scripts/tests/commit-gate-timeout.test.sh.
#
# Модель фаз здесь — ВЕРХНЯЯ оценка. Замер боевого пути 2026-08-18 (macOS,
# нативного timeout/gtimeout нет, работает Python-ветка помощника) дал 1,12 с на
# добивание против модельных 2 с и 0,10 с на запуск фазы против модельной 1 с,
# то есть НАБЛЮДЁННЫЙ путь ≈ 583 с при запасе ≈ 17 с. Именно наблюдённый, а не
# «худший»: замеры одиночные и сделаны на незагруженной машине, а нормальная
# среда этого гейта — loadavg 6–24 (см. серию ниже), где растягивается и
# добивание. Запас 15 с берётся как раз на это расхождение модели с фактом.
#
# ПОЧЕМУ ОБЪЯВЛЕННЫЙ ДИСПЕТЧЕРУ ПРЕДЕЛ РАВЕН 600 с, А НЕ БОЛЬШЕ. 600 с — это
# документированное значение по умолчанию для hook'ов типа `command` в Claude
# Code. Верхнего предела для поля `timeout` документация не называет, то есть
# значение выше умолчания опиралось бы на недокументированное поведение: если бы
# диспетчер молча урезал объявленное число, он снял бы обработчик раньше его
# собственного вердикта — а снятый PreToolUse-обработчик команду НЕ блокирует
# (промах в небезопасную сторону, прямая цитата документации: «don't count on a
# stalled hook to act as a gate»). На умолчании этой развилки нет: значение,
# равное дефолту, диспетчер поддерживает при любом из двух поведений. Поэтому
# 600 — потолок пакета, и он закреплён тестом commit-gate-timeout.test.sh.
# Источник умолчания: https://code.claude.com/docs/en/hooks.md, раздел «Common
# fields», сверено 2026-08-18 — «Defaults: 600 for command, http, and mcp_tool».
set -uo pipefail

# Формат величины времени — ОДНО правило на все три предела пакета (прогон,
# разбор, остаточный запас) и на оба тестовых крючка: целое число секунд больше
# нуля БЕЗ ВЕДУЩЕГО НУЛЯ.
#
# Ведущий ноль запрещён потому, что число живёт в ДВУХ разных арифметиках. Сам
# гейт передаёт его помощнику времени как строку, и `0571` отработает как 571 с.
# Но бюджет считает арифметика оболочки в тестах, а она читает `0571` как
# ВОСЬМЕРИЧНОЕ 377. Расхождение однонаправленное и в небезопасную сторону:
# фактический бюджет 586 с при зазоре 29 с проходит проверки, которые считают
# его 392-секундным. Проверено мутациями `0571` и `011` — обе оставляли оба
# гейт-теста зелёными до появления этого правила. Форма правдоподобна
# (выравнивание колонок, привычка к нулевому дополнению), поэтому значение
# отвергается, а не молча пересчитывается.
#
# Правило заведено ОДНО на пакет намеренно: прежде проверка формата была
# продублирована по месту у каждого предела, и починка ведущего нуля у одного
# из них оставила бы два других открытыми — ровно это и нашёл внешний проход.
valid_seconds_format() {
  case "$1" in
    ''|*[!0-9]*) return 1 ;;
    0*) return 1 ;;
  esac
  [ "$1" -gt 0 ] || return 1
  return 0
}

# Остаточный запас между бюджетом фаз и объявленным диспетчеру пределом, секунды.
#
# Число живёт ЗДЕСЬ, а не в тесте, намеренно. Обещание «запас ≥ 15 с» даёт
# таблица выше — то есть этот файл; значит и величина обещания обязана лежать в
# нём же, иначе проза и механизм расходятся молча (ровно так и родился дефект,
# который чинит фикс-раунд: тест допускал нулевой запас, а таблица обещала 15 с).
# Тест commit-gate-parse-budget.test.sh читает это значение через
# --print-reserve-seconds и не держит своей копии.
#
# Честная граница: правка ЭТОГО числа вниз тест не покрасит — он проверяет
# согласованность бюджета с обещанием, а не само обещание. Защита здесь в том,
# что обещание и его величина теперь в одном файле и правятся одной видимой
# правкой гейта, а не тихой правкой числа внутри проверки.
DISPATCHER_RESERVE_SECONDS=15

# Значение обещания проверяется здесь же, а не только у потребителя, и по тем же
# правилам, что оба соседних предела: целое число секунд больше нуля И БЕЗ
# ВЕДУЩЕГО НУЛЯ. Ведущий ноль — не придирка к стилю: арифметика оболочки читает
# `015` как восьмеричное 13, поэтому напечатано было бы 15, а применено 13 —
# промах в небезопасную сторону при полностью зелёном наборе (проверено:
# бюджет 586 при `15` краснеет, при `015` проходит). Форма выравнивания колонок
# «15 → 015» правдоподобна, поэтому она отвергается, а не молча пересчитывается.
effective_reserve_seconds() {
  valid_seconds_format "$DISPATCHER_RESERVE_SECONDS" || return 1
  printf '%s\n' "$DISPATCHER_RESERVE_SECONDS"
}

# Собственный предел РАЗБОРА команды, секунды. Разбор — отдельная фаза до
# прогона набора, и раньше она шла вообще без предела: зависший классификатор
# съедал бюджет обработчика целиком, диспетчер снимал гейт, и коммит уходил без
# проверки. Замер классификатора в этом репозитории (2026-08-12, macOS): 0,05 с
# на команду любой из проверяемых форм, включая 24 уровня вложенных подстановок.
# 10 с — двухсоткратный запас; всё, что дольше, разбором не является.
CLASSIFY_TIMEOUT_SECONDS=10

# Собственный предел ожидания набора тестов, секунды.
#
# Значение 570/600 сохранено из source; reference suite должен укладываться в бюджет.
# Project suite калибруется отдельно, timeout failure блокирует commit.
GATE_TIMEOUT_SECONDS=570

# Тестовый крючок: СУЖАЕТ окно ожидания, чтобы поведение по истечении предела
# проверялось за секунды, а не за минуты. Берётся минимум с рабочим пределом,
# поэтому расширить окно крючком нельзя — он не может превратить блокирующий
# гейт в пропускающий. Значение вне формата выше трактуется как неисправная
# настройка и блокирует.
effective_timeout_seconds() {
  local limit="$GATE_TIMEOUT_SECONDS"
  local override="${OVERGATE_COMMIT_GATE_TEST_MAX_SECONDS-}"
  valid_seconds_format "$limit" || return 1
  if [ -n "$override" ]; then
    valid_seconds_format "$override" || return 1
    if [ "$override" -lt "$limit" ]; then
      limit="$override"
    fi
  fi
  printf '%s\n' "$limit"
}

# Тот же крючок для фазы разбора: тоже только СУЖАЕТ окно (берётся минимум),
# поэтому им нельзя превратить блокирующий гейт в пропускающий.
effective_classify_timeout_seconds() {
  local limit="$CLASSIFY_TIMEOUT_SECONDS"
  local override="${OVERGATE_COMMIT_GATE_TEST_MAX_CLASSIFY_SECONDS-}"
  valid_seconds_format "$limit" || return 1
  if [ -n "$override" ]; then
    valid_seconds_format "$override" || return 1
    if [ "$override" -lt "$limit" ]; then
      limit="$override"
    fi
  fi
  printf '%s\n' "$limit"
}

# Диагностические режимы для тестов соответствия: печатают действующий предел,
# ничего не запуская. Диспетчер вызывает hook без аргументов, поэтому на боевой
# путь режимы не влияют. Проверяются ДО чтения stdin — они не ждут payload.
if [ "${1-}" = "--print-timeout-seconds" ]; then
  if PRINT_LIMIT="$(effective_timeout_seconds)"; then
    printf '%s\n' "$PRINT_LIMIT"
    exit 0
  fi
  echo "БЛОКИРОВКА: предел времени гейта задан неверно — ожидалось целое число секунд больше нуля без ведущего нуля." >&2
  exit 2
fi

if [ "${1-}" = "--print-reserve-seconds" ]; then
  if PRINT_RESERVE="$(effective_reserve_seconds)"; then
    printf '%s\n' "$PRINT_RESERVE"
    exit 0
  fi
  echo "БЛОКИРОВКА: остаточный запас задан неверно — ожидалось целое число секунд больше нуля без ведущего нуля." >&2
  exit 2
fi

if [ "${1-}" = "--print-classify-timeout-seconds" ]; then
  if PRINT_LIMIT="$(effective_classify_timeout_seconds)"; then
    printf '%s\n' "$PRINT_LIMIT"
    exit 0
  fi
  echo "БЛОКИРОВКА: предел времени разбора задан неверно — ожидалось целое число секунд больше нуля без ведущего нуля." >&2
  exit 2
fi

PAYLOAD="$(cat)"
HOOK_PATH="${BASH_SOURCE[0]}"
case "$HOOK_PATH" in
  */*) HOOK_DIR="${HOOK_PATH%/*}" ;;
  *) HOOK_DIR="." ;;
esac
HOOK_DIR="$(cd -- "$HOOK_DIR" && pwd)"
CLASSIFIER="$HOOK_DIR/commit_command_classifier.py"
PYTHON_LAUNCHER="$HOOK_DIR/../tools/run-python.sh"
TIMEOUT_HELPER="$HOOK_DIR/../tools/with-timeout.sh"

# Единый launcher проверяет реальный Python 3 и переносимо поддерживает py -3,
# python3 и python. Любая его ошибка блокирует fail-closed.
if [ ! -x "$PYTHON_LAUNCHER" ]; then
  echo "БЛОКИРОВКА: переносимый Python launcher отсутствует или не исполним, гейт тестов не может проверить команду." >&2
  exit 2
fi

# Помощник ограничения времени нужен ОБЕИМ фазам, поэтому проверяется до разбора.
# Без него гейт не может доказать, что фаза завершилась до снятия обработчика
# диспетчером, — значит блокирует.
if [ ! -x "$TIMEOUT_HELPER" ]; then
  echo "БЛОКИРОВКА: помощник ограничения времени отсутствует или не исполним, гейт тестов не может дождаться результата." >&2
  exit 2
fi

if ! CLASSIFY_LIMIT="$(effective_classify_timeout_seconds)"; then
  echo "БЛОКИРОВКА: предел времени разбора задан неверно — ожидалось целое число секунд больше нуля без ведущего нуля." >&2
  exit 2
fi

CLASSIFICATION="$(printf '%s' "$PAYLOAD" | \
  "$TIMEOUT_HELPER" "$CLASSIFY_LIMIT" "$PYTHON_LAUNCHER" "$CLASSIFIER" classify-hook 2>/dev/null)"
RC=$?

# Код 124 — истечение собственного предела обёртки. Разбор не завершён, значит
# доказательства «команда не является коммитом» нет, и команда не пропускается.
if [ "$RC" -eq 124 ]; then
  echo "БЛОКИРОВКА: разбор команды не уложился в предел $CLASSIFY_LIMIT с, поэтому команда не пропускается: доказать, что это не коммит, невозможно." >&2
  exit 2
fi
if [ "$RC" -ne 0 ]; then
  echo "БЛОКИРОВКА: классификатор commit-команд не смог разобрать вход хука (код $RC)." >&2
  exit 2
fi

case "$CLASSIFICATION" in
  ordinary) exit 0 ;;
  commit) ;;
  ambiguous)
    echo "БЛОКИРОВКА: команда может скрывать git commit, но классификатор не доказал точную commit-операцию." >&2
    echo "Используй явный git commit после проверок; тяжёлый test-suite для ambiguous-команды не запускается." >&2
    exit 2
    ;;
  *)
    echo "БЛОКИРОВКА: классификатор commit-команд вернул неизвестный класс." >&2
    exit 2
    ;;
esac

if ! GATE_LIMIT="$(effective_timeout_seconds)"; then
  echo "БЛОКИРОВКА: предел времени гейта задан неверно — ожидалось целое число секунд больше нуля без ведущего нуля." >&2
  exit 2
fi

# Наличие помощника ограничения времени уже проверено перед фазой разбора.
"$TIMEOUT_HELPER" "$GATE_LIMIT" bash "$HOOK_DIR/../../.agents/project/verify.sh"
TEST_RC=$?

if [ "$TEST_RC" -eq 0 ]; then
  exit 0
fi

# Код 124 — истечение собственного предела обёртки. Разделяем его с обычным
# падением тестов: причина блокировки разная, и разработчику нужно видеть, что
# результат вообще не получен, а не что тесты красные.
if [ "$TEST_RC" -eq 124 ]; then
  echo "БЛОКИРОВКА: набор тестов не уложился в предел $GATE_LIMIT с, результат не получен. Коммит не пропускается." >&2
  exit 2
fi

echo "БЛОКИРОВКА: тесты падают. Исправь перед коммитом." >&2
exit 2
